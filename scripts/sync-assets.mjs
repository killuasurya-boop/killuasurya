// Copies (never moves) original Owner assets into public/ and generates
// src/assets/doodles.generated.ts with the ORIGINAL SVG markup (verbatim) so
// doodles can be stroke-animated without being redrawn.
// Usage: SOURCE_UI="<path to KILLUASIRUA.tech/UI/komponen>" node scripts/sync-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const src = process.env.SOURCE_UI ?? path.resolve('..', 'UI', 'komponen');
const out = path.resolve('public/assets/killuasurya');
const groups = ['01_CHARACTERS', '02_DOODLES', '03_ARROWS', '04_OBJECTS'];
const registry = [];
const inline = {};

for (const g of groups) {
  fs.mkdirSync(path.join(out, 'creative', g), { recursive: true });
  for (const f of fs.readdirSync(path.join(src, g)).filter((n) => n.endsWith('.svg')).sort()) {
    const buf = fs.readFileSync(path.join(src, g, f));
    fs.writeFileSync(path.join(out, 'creative', g, f), buf);
    registry.push({ file: `creative/${g}/${f}`, source: `UI/komponen/${g}/${f}`, md5: crypto.createHash('md5').update(buf).digest('hex') });
    if (g === '02_DOODLES' || g === '03_ARROWS') {
      const key = f.replace(/^\d+_/, '').replace('.svg', '');
      inline[key] = buf.toString('utf8').replace(/<title[^>]*>.*?<\/title>/s, '').replace(/<desc[^>]*>.*?<\/desc>/s, '')
        .replace(/ role="img"/, ' aria-hidden="true" focusable="false"').replace(/ aria-labelledby="[^"]*"/, '');
    }
  }
}

// Owner originals delivered directly (chat, 12 Nov 2026) live in ./assets-src — copied, never modified.
const extra = path.resolve('assets-src');
const hiRes = { 'mascot-hero-thumbs-up-1600.png': 'hero-thumbs-up.png', 'mascot-hero-idea-thinking-1600.png': 'hero-idea-thinking.png' };
fs.mkdirSync(path.join(out, 'brand'), { recursive: true });
for (const f of fs.existsSync(extra) ? fs.readdirSync(extra).sort() : []) {
  const buf = fs.readFileSync(path.join(extra, f));
  const md5 = crypto.createHash('md5').update(buf).digest('hex');
  if (f.endsWith('.svg')) {
    fs.writeFileSync(path.join(out, 'brand', f), buf);
    inline[f.replace(/^\d+_/, '').replace('.svg', '')] = buf.toString('utf8').replace(/<title[^>]*>.*?<\/title>/s, '').replace(/<desc[^>]*>.*?<\/desc>/s, '')
      .replace(/ role="img"/, ' aria-hidden="true" focusable="false"').replace(/ aria-label="[^"]*"/, '').replace(/ id="[^"]*"/g, '');
    registry.push({ file: `brand/${f}`, source: `assets-src/${f} (Owner, chat 12 Nov 2026)`, md5 });
  }
}

// Original mascot art. Preferred: Owner's high-res transparent PNGs (assets-src). Fallback: raster embedded in 04/05 SVGs.
fs.mkdirSync(path.join(out, 'mascot'), { recursive: true });
for (const [svg, png] of [['04_mascot_hero_thumbs_up.svg', 'hero-thumbs-up.png'], ['05_mascot_idea_thinking.svg', 'hero-idea-thinking.png']]) {
  const hi = Object.keys(hiRes).find((k) => hiRes[k] === png && fs.existsSync(path.join(extra, k)));
  let b, source;
  if (hi) { b = fs.readFileSync(path.join(extra, hi)); source = `assets-src/${hi} (Owner high-res, chat 12 Nov 2026)`; }
  else {
    const t = fs.readFileSync(path.join(src, svg), 'utf8');
    b = Buffer.from(t.match(/base64,([A-Za-z0-9+/=]+)/)[1], 'base64');
    source = `UI/komponen/${svg} (embedded PNG, extracted unmodified)`;
  }
  fs.writeFileSync(path.join(out, 'mascot', png), b);
  registry.push({ file: `mascot/${png}`, source, md5: crypto.createHash('md5').update(b).digest('hex') });
}

fs.writeFileSync(path.resolve('src/assets/doodles.generated.ts'),
  '// AUTO-GENERATED by scripts/sync-assets.mjs — original Owner SVG markup, do not edit by hand.\n' +
  `export const doodles = ${JSON.stringify(inline, null, 2)} as const;\nexport type DoodleName = keyof typeof doodles;\n`);
registry.push({ file: 'brand/logo-killuasurya-tech.png', source: 'assets-src/logo-killuasurya-tech-original.png (Owner official logo, chat 12 Nov 2026). Derivative: solid dark background keyed to transparent + cropped; artwork untouched.', md5: fs.existsSync(path.join(out, 'brand', 'logo-killuasurya-tech.png')) ? crypto.createHash('md5').update(fs.readFileSync(path.join(out, 'brand', 'logo-killuasurya-tech.png'))).digest('hex') : null });
fs.writeFileSync(path.resolve('docs/ASSET_REGISTRY.json'), JSON.stringify(registry, null, 2));
console.log(`synced ${registry.length} assets, ${Object.keys(inline).length} inline doodles`);
